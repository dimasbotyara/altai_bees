@app.route("/")
def index():
    return render_template("index.html")


@app.route("/api/definition/<word>")
def get_definition(word):
    word = word.lower()
    if word in DEFINITIONS:
        return jsonify(random.choice(DEFINITIONS[word]))
    return jsonify({"error": "Слово не найдено"}), 404


